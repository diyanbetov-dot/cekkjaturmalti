from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import Sequence


class FailureCategory(StrEnum):
    GENERATION_FAILURE = "generation_failure"
    PRUNING_FAILURE = "pruning_failure"
    SEARCH_FAILURE = "search_failure"
    RANKING_FAILURE = "ranking_failure"
    S1_CORRUPTION_LEAK = "s1_corruption_leak"
    UNKNOWN = "unknown"


@dataclass(frozen=True, slots=True)
class FailureRecord:
    example_id: str
    raw_text: str
    predicted_text: str
    target_text: str
    category: FailureCategory
    details: str


@dataclass(frozen=True, slots=True)
class FailureReport:
    total_failures: int
    category_counts: dict[str, int]
    records: tuple[FailureRecord, ...]


def categorize_failure(
    example_id: str,
    raw_text: str,
    predicted_text: str,
    target_text: str,
    gold_in_lattice: bool = True,
    gold_in_search: bool = True,
    s1_corrupted_raw: bool = False,
) -> FailureRecord:
    if predicted_text == target_text:
        raise ValueError("Cannot categorize a successful prediction as a failure.")

    if not gold_in_lattice:
        cat = FailureCategory.GENERATION_FAILURE
        details = "Gold candidate not generated by candidate sources."
    elif not gold_in_search:
        cat = FailureCategory.PRUNING_FAILURE
        details = "Gold candidate pruned during lattice filtering."
    elif s1_corrupted_raw:
        cat = FailureCategory.S1_CORRUPTION_LEAK
        details = "Stage 1 context corrupted raw text features."
    else:
        cat = FailureCategory.RANKING_FAILURE
        details = "Ranker scored incorrect candidate above gold path."

    return FailureRecord(
        example_id=example_id,
        raw_text=raw_text,
        predicted_text=predicted_text,
        target_text=target_text,
        category=cat,
        details=details,
    )


def summarize_failures(records: Sequence[FailureRecord]) -> FailureReport:
    counts: dict[str, int] = {cat.value: 0 for cat in FailureCategory}
    for rec in records:
        counts[rec.category.value] = counts.get(rec.category.value, 0) + 1
    return FailureReport(
        total_failures=len(records),
        category_counts=counts,
        records=tuple(records),
    )
